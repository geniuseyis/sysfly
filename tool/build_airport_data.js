// Builds the airport catalogue and localized country names shipped with the app.
//
//   node tool/build_airport_data.js
//
// Sources (downloaded on each run):
//   - OurAirports airports.csv and countries.csv (public domain)
//   - OpenFlights airports.dat, used only for UTC offsets (Open Database License)
//   - Unicode CLDR territory names (Unicode License)
//
// Output:
//   - assets/data/airports.tsv        code, name, city, country code, continent, lat, lon, UTC offset
//   - lib/data/generated/country_names.dart
const fs = require('fs');
const https = require('https');

const LANGS = ['en', 'tr', 'de', 'fr', 'es', 'ru', 'ar'];

function get(url) {
  return new Promise((resolve, reject) => {
    https.get(url, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) return resolve(get(res.headers.location));
      if (res.statusCode !== 200) return reject(new Error(`${res.statusCode} for ${url}`));
      const chunks = [];
      res.on('data', (c) => chunks.push(c));
      res.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
    }).on('error', reject);
  });
}

/// Minimal CSV parser that understands quoted fields.
function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else quoted = false; } else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c !== '\r') field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

function shortName(name) {
  return name
    .replace(/\s+International Airport$/i, ' Intl')
    .replace(/\s+Airport$/i, '')
    .replace(/\bInternational\b/gi, 'Intl')
    .replace(/\s+/g, ' ')
    .trim();
}

(async () => {
  const [airportsCsv, openFlights, ...cldr] = await Promise.all([
    get('https://davidmegginson.github.io/ourairports-data/airports.csv'),
    get('https://raw.githubusercontent.com/jpatokal/openflights/master/data/airports.dat'),
    ...LANGS.map((l) => get(`https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-localenames-full/main/${l}/territories.json`)),
  ]);

  // UTC offsets by IATA code.
  const offsets = {};
  for (const r of parseCsv(openFlights)) {
    if (r[4] && r[4] !== '\\N' && r[9] && r[9] !== '\\N') offsets[r[4]] = Number(r[9]);
  }

  const rows = parseCsv(airportsCsv);
  const h = Object.fromEntries(rows[0].map((n, i) => [n, i]));
  const keep = new Set(['large_airport', 'medium_airport', 'small_airport']);
  const seen = new Set();
  const out = [];
  for (const r of rows.slice(1)) {
    const code = r[h.iata_code];
    if (!code || code.length !== 3 || seen.has(code)) continue;
    if (!keep.has(r[h.type]) || r[h.scheduled_service] !== 'yes') continue;
    const lat = Number(r[h.latitude_deg]), lon = Number(r[h.longitude_deg]);
    const city = (r[h.municipality] || '').split(/[\/(]/)[0].trim() || shortName(r[h.name]);
    // Longitude gives a rough offset where OpenFlights has none.
    const offset = offsets[code] ?? Math.round(lon / 15);
    seen.add(code);
    out.push({ rank: r[h.type] === 'large_airport' ? 0 : r[h.type] === 'medium_airport' ? 1 : 2,
      line: [code, shortName(r[h.name]), city, r[h.iso_country], r[h.continent], lat.toFixed(4), lon.toFixed(4), offset].join('\t') });
  }
  // Larger airports first so they lead search results.
  out.sort((a, b) => a.rank - b.rank || a.line.localeCompare(b.line));
  fs.mkdirSync('assets/data', { recursive: true });
  fs.writeFileSync('assets/data/airports.tsv', out.map((o) => o.line).join('\n') + '\n');

  // Country names in every app language, for the countries that have airports.
  const used = [...new Set(out.map((o) => o.line.split('\t')[3]))].sort();
  const names = LANGS.map((l, i) => JSON.parse(cldr[i]).main[l].localeDisplayNames.territories);
  const esc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
  const lines = [
    '// GENERATED by tool/build_airport_data.js from Unicode CLDR. Do not edit.',
    '',
    `/// Country names by ISO code, in the order: ${LANGS.join(', ')}.`,
    'const Map<String, List<String>> kCountryNames = {',
    ...used.map((cc) => `  '${cc}': [${names.map((n) => `'${esc(n[cc + '-alt-short'] || n[cc] || cc)}'`).join(', ')}],`),
    '};',
    '',
  ];
  fs.mkdirSync('lib/data/generated', { recursive: true });
  fs.writeFileSync('lib/data/generated/country_names.dart', lines.join('\n'));
  console.log(`airports: ${out.length}, countries: ${used.length}, with real offset: ${out.filter((o) => offsets[o.line.slice(0, 3)] !== undefined).length}`);
})().catch((e) => { console.error(e.message); process.exit(1); });
